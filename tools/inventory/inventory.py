"""Reproducible inventory of the C++ baseline (migration plan §4, Phase 0).

Generates versioned markdown reports into docs/inventory/:

    loc.md                     line census by area
    singletons.md              global `TheXxx` singleton declarations
    retail-compat-switches.md  RETAIL_COMPATIBLE_* switch table
    platform-coupling.md       platform/technology coupling counts
    rts-forks.md               RTS_GENERALS vs RTS_ZEROHOUR forks

Usage:
    python3 tools/inventory/inventory.py [--out docs/inventory]

The reports record the commit they were generated from; regenerate after
cherry-picking upstream logic fixes. Deterministic: no timestamps, sorted
output.
"""

from __future__ import annotations

import argparse
import pathlib
import re
import subprocess
import sys
from collections import Counter

SOURCE_SUFFIXES = {".cpp", ".h", ".c", ".hpp", ".inl"}

# Areas measured by the migration plan (§2). (path, label)
AREAS = [
    ("Core/GameEngine", "Core/GameEngine"),
    ("Core/GameEngineDevice", "Core/GameEngineDevice"),
    ("Core/Libraries", "Core/Libraries"),
    ("GeneralsMD/Code/GameEngine", "GeneralsMD/Code/GameEngine"),
    ("GeneralsMD/Code/GameEngineDevice", "GeneralsMD/Code/GameEngineDevice"),
    ("GeneralsMD/Code/Libraries", "GeneralsMD/Code/Libraries"),
    ("Dependencies", "Dependencies"),
    ("Core/Tools", "Core/Tools"),
    ("GeneralsMD/Code/Tools", "GeneralsMD/Code/Tools"),
    ("Generals", "Generals/ (base game, dropped)"),
    ("Tests", "Tests"),
    ("Benchmarks", "Benchmarks"),
]

SKIP_DIRS = {".git", "target", "GeneralsReplays", "build", "node_modules"}

SINGLETON_RE = re.compile(r"^\s*extern\s+\w+\s*\*\s*(The\w+)", re.MULTILINE)
RETAIL_SWITCH_RE = re.compile(r"RETAIL_COMPATIBLE[A-Z_]*")
RTS_FORK_RE = re.compile(r"\b(RTS_GENERALS|RTS_ZEROHOUR)\b")


def repo_root() -> pathlib.Path:
    return pathlib.Path(__file__).resolve().parent.parent.parent


def git_ref(root: pathlib.Path) -> str:
    try:
        return subprocess.run(
            ["git", "rev-parse", "--short", "HEAD"],
            cwd=root, capture_output=True, text=True, check=True,
        ).stdout.strip()
    except (subprocess.CalledProcessError, OSError):
        return "unknown"


def source_files(root: pathlib.Path) -> list[pathlib.Path]:
    files = []
    for path in root.rglob("*"):
        if not path.is_file():
            continue
        if any(part in SKIP_DIRS for part in path.relative_to(root).parts):
            continue
        if path.suffix.lower() in SOURCE_SUFFIXES:
            files.append(path)
    return sorted(files)


def read(path: pathlib.Path) -> str:
    try:
        return path.read_text(encoding="utf-8", errors="replace")
    except OSError:
        return ""


def write_report(root: pathlib.Path, out_dir: pathlib.Path, name: str, body: str) -> None:
    ref = git_ref(root)
    content = (
        f"<!-- Generated by tools/inventory/inventory.py from the working tree at {ref}. "
        f"Do not edit by hand; regenerate instead. -->\n\n" + body
    )
    target = out_dir / name
    target.write_text(content, encoding="utf-8")
    print(f"wrote {target.relative_to(root)}")


def area_of(path: pathlib.Path, root: pathlib.Path) -> str | None:
    rel = path.relative_to(root)
    parts = rel.parts
    for prefix, label in AREAS:
        prefix_parts = tuple(prefix.split("/"))
        if parts[: len(prefix_parts)] == prefix_parts:
            return label
    return None


def generate_loc(root: pathlib.Path, out_dir: pathlib.Path, files: list[pathlib.Path]) -> None:
    lines = [
        "# Line census of the C++ baseline",
        "",
        "Counts lines in `*.cpp *.h *.c *.hpp *.inl` (comments and blank lines",
        "included), reproducing and versioning the measurements of migration",
        "plan §2. Areas marked **dropped** are not ported.",
        "",
        "| Area | Files | Lines | Porting strategy |",
        "|---|---:|---:|---|",
    ]
    strategy = {
        "Core/GameEngine": "Port (common, game logic, client, network)",
        "Core/GameEngineDevice": "Re-implement (W3DDevice, Miles, video, Win32)",
        "Core/Libraries": "Mixed: WW3D2, WWLib, WWMath, WWAudio, compression",
        "GeneralsMD/Code/GameEngine": "Port: the heart (GameLogic, GameClient, Common)",
        "GeneralsMD/Code/GameEngineDevice": "Re-implement (renderer glue)",
        "GeneralsMD/Code/Libraries": "Mixed (WWVegas additions)",
        "Dependencies": "Replace",
        "Core/Tools": "Defer (Phase 8)",
        "GeneralsMD/Code/Tools": "Defer (Phase 8)",
        "Generals/ (base game, dropped)": "**Dropped**",
        "Tests": "Reference for the first Rust tests",
        "Benchmarks": "Reference for Rust benchmarks",
    }
    per_area: Counter[str] = Counter()
    files_per_area: Counter[str] = Counter()
    total_lines = 0
    unaccounted = 0
    for path in files:
        count = len(read(path).splitlines())
        total_lines += count
        area = area_of(path, root)
        if area is None:
            unaccounted += count
        else:
            per_area[area] += count
            files_per_area[area] += 1
    for _, label in AREAS:
        lines.append(
            f"| {label} | {files_per_area[label]} | {per_area[label]} | {strategy[label]} |"
        )
    if unaccounted:
        lines.append(f"| (outside the measured areas) | – | {unaccounted} | – |")
    lines.append(f"| **Total** | **{len(files)}** | **{total_lines}** | |")
    lines.append("")
    write_report(root, out_dir, "loc.md", "\n".join(lines))


def generate_singletons(root: pathlib.Path, out_dir: pathlib.Path, files: list[pathlib.Path]) -> None:
    names: Counter[str] = Counter()
    declared_in: dict[str, set[str]] = {}
    for path in files:
        parts = path.relative_to(root).parts
        if parts[0] not in {"Core", "GeneralsMD"} or "Include" not in parts:
            continue
        text = read(path)
        for match in SINGLETON_RE.finditer(text):
            name = match.group(1)
            names[name] += 1
            declared_in.setdefault(name, set()).add(str(path.relative_to(root)))
    lines = [
        "# Global singleton declarations",
        "",
        "`extern` declarations of `TheXxx` global pointers in `Core/` and",
        "`GeneralsMD/` headers. The Rust design replaces them with explicit",
        "contexts (migration plan §2 observation 2 and §3.3 rule 5).",
        "",
        f"{len(names)} distinct singletons declared.",
        "",
        "| Singleton | Declarations | Declared in |",
        "|---|---:|---|",
    ]
    for name in sorted(names):
        locations = "<br>".join(sorted(declared_in[name]))
        lines.append(f"| `{name}` | {names[name]} | {locations} |")
    lines.append("")
    write_report(root, out_dir, "singletons.md", "\n".join(lines))


def generate_retail_switches(
    root: pathlib.Path, out_dir: pathlib.Path, files: list[pathlib.Path]
) -> None:
    counts: Counter[str] = Counter()
    file_counts: Counter[str] = Counter()
    for path in files:
        text = read(path)
        found = set(RETAIL_SWITCH_RE.findall(text))
        for switch in found:
            counts[switch] += len(re.findall(re.escape(switch), text))
            file_counts[switch] += 1
    lines = [
        "# `RETAIL_COMPATIBLE_*` switches",
        "",
        "Behaviour-fix gates inherited from the upstream project. The Rust",
        "port follows the **non-retail (fixed) branch** of every switch",
        "(ADR-000); each switch is verified individually in Phase 0/1 as its",
        "code is ported.",
        "",
        "| Switch | References | Files | Branch ported |",
        "|---|---:|---:|---|",
    ]
    for switch in sorted(counts):
        lines.append(f"| `{switch}` | {counts[switch]} | {file_counts[switch]} | non-retail |")
    lines.append("")
    total_files = len({p for p in files if RETAIL_SWITCH_RE.search(read(p))})
    lines.append(f"Total files referencing at least one switch: **{total_files}**.")
    lines.append("")
    write_report(root, out_dir, "retail-compat-switches.md", "\n".join(lines))


def generate_platform_coupling(
    root: pathlib.Path, out_dir: pathlib.Path, files: list[pathlib.Path]
) -> None:
    patterns = {
        "windows.h": re.compile(r"#include\s*[<\"]windows\.h[>\"]"),
        "d3d8": re.compile(r"\bd3d8\b", re.IGNORECASE),
        "Bink": re.compile(r"\bBink\b"),
        "Miles": re.compile(r"\bMiles\b"),
        "inline asm (__asm)": re.compile(r"\b__asm\b"),
        "DirectX (d3d8/d3dx)": re.compile(r"\bd3d8\b|\bd3dx\d", re.IGNORECASE),
    }
    counts = {label: 0 for label in patterns}
    for path in files:
        text = read(path)
        for label, pattern in patterns.items():
            if pattern.search(text):
                counts[label] += 1
    lines = [
        "# Platform and technology coupling",
        "",
        "Number of C/C++ files whose contents reference each technology.",
        "These motivate the re-implement (not port) strategy for the device",
        "layers (migration plan §2 observation 5).",
        "",
        "| Coupling | Files | Disposition |",
        "|---|---:|---|",
    ]
    disposition = {
        "windows.h": "Platform layer re-implemented in Rust",
        "d3d8": "Renderer re-implemented on wgpu",
        "DirectX (d3d8/d3dx)": "Renderer re-implemented on wgpu",
        "Bink": "Replaced by an open video path (ADR-007)",
        "Miles": "Audio engine re-implemented (ADR-006)",
        "inline asm (__asm)": "Rewritten in safe Rust with the same semantics",
    }
    for label in patterns:
        lines.append(f"| {label} | {counts[label]} | {disposition[label]} |")
    lines.append("")
    write_report(root, out_dir, "platform-coupling.md", "\n".join(lines))


def generate_rts_forks(root: pathlib.Path, out_dir: pathlib.Path, files: list[pathlib.Path]) -> None:
    counts: Counter[str] = Counter()
    file_counts: Counter[str] = Counter()
    for path in files:
        text = read(path)
        for fork in set(RTS_FORK_RE.findall(text)):
            counts[fork] += len(re.findall(rf"\b{fork}\b", text))
            file_counts[fork] += 1
    lines = [
        "# Shared-code forks: `RTS_GENERALS` vs `RTS_ZEROHOUR`",
        "",
        "`Core/` contains both games behind these macros. The Rust port",
        "follows the **Zero Hour branch only** (ADR-000); the base-game",
        "`Generals/` tree is dropped.",
        "",
        "| Macro | References | Files | Ported? |",
        "|---|---:|---:|---|",
    ]
    ported = {"RTS_ZEROHOUR": "yes (this is the target)", "RTS_GENERALS": "no (dropped)"}
    for fork in sorted(counts):
        lines.append(f"| `{fork}` | {counts[fork]} | {file_counts[fork]} | {ported[fork]} |")
    lines.append("")
    write_report(root, out_dir, "rts-forks.md", "\n".join(lines))


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--out", default="docs/inventory", help="output directory (default: docs/inventory)"
    )
    args = parser.parse_args()

    root = repo_root()
    out_dir = root / args.out
    out_dir.mkdir(parents=True, exist_ok=True)

    files = source_files(root)
    if not files:
        print("error: no source files found", file=sys.stderr)
        return 1

    generate_loc(root, out_dir, files)
    generate_singletons(root, out_dir, files)
    generate_retail_switches(root, out_dir, files)
    generate_platform_coupling(root, out_dir, files)
    generate_rts_forks(root, out_dir, files)
    print(f"inventory of {len(files)} source files complete")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
