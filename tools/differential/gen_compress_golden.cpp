// Golden-vector generator for the rzh-compress::refpack port.
//
// Like gen_gmath_golden.c, this driver avoids a second transcription: it
// compiles and calls the REAL codec sources from the game tree
// (Core/Libraries/Source/Compression/EAC/refdecode.cpp and refencode.cpp)
// at the baseline commit. The Rust port must match these outputs
// byte-for-byte, in both directions (parity level P0).
//
// Original: Copyright (C) Electronic Arts Canada Inc. 1995-2002.
//
// Usage (wired up by tools/differential/regenerate.sh):
//   gen_compress_golden <out.txt>
//
// Output format (hex, no prefixes):
//   refpack encode <input-hex> <compressed-hex>
//   refpack decode <compressed-hex> <decoded-hex> <compressedsize-dec>
//   refpack size <compressed-hex> <size-dec>

#include <cstdint>
#include <cstdio>
#include <cstring>
#include <string>
#include <vector>

// The real codec sources, compiled as separate translation units and
// linked into this driver (exactly how the game builds them). The
// declarations below mirror refcodex.h without its default arguments
// (the header has no include guard and cannot be included twice).
extern "C" {
bool REF_is(const void *compresseddata);
int REF_size(const void *compresseddata);
int REF_decode(void *dest, const void *compresseddata, int *compressedsize);
int REF_encode(void *compresseddata, const void *source, int sourcesize, int *opts);
}

// Deterministic LCG so the vector set is reproducible.
static uint32_t lcg_state = 0xc0ffee11u;
static uint32_t lcg(void) {
    lcg_state = lcg_state * 1664525u + 1013904223u;
    return lcg_state;
}

static std::string hex(const std::vector<uint8_t> &bytes) {
    static const char *digits = "0123456789abcdef";
    std::string out;
    out.reserve(bytes.size() * 2);
    for (uint8_t b : bytes) {
        out.push_back(digits[b >> 4]);
        out.push_back(digits[b & 15]);
    }
    if (out.empty())
        out.push_back('-');
    return out;
}

static void emit_round(FILE *out, const std::vector<uint8_t> &input) {
    // encode (dest buffer generously sized; REF_encode returns the length)
    std::vector<uint8_t> packed(input.size() + input.size() / 2 + 1024, 0);
    int plen = REF_encode(packed.data(), input.data(), (int)input.size(), nullptr);
    packed.resize(plen > 0 ? (size_t)plen : 0);

    fprintf(out, "refpack encode %s %s\n", hex(input).c_str(), hex(packed).c_str());

    // size + decode of our own encoding (round trip through the C code)
    fprintf(out, "refpack size %s %d\n", hex(packed).c_str(), REF_size(packed.data()));

    std::vector<uint8_t> unpacked((size_t)REF_size(packed.data()) + 16, 0);
    int consumed = 0;
    int ulen = REF_decode(unpacked.data(), packed.data(), &consumed);
    unpacked.resize(ulen > 0 ? (size_t)ulen : 0);
    fprintf(out, "refpack decode %s %s %d\n", hex(packed).c_str(),
            hex(unpacked).c_str(), consumed);
}

int main(int argc, char **argv) {
    if (argc != 2) {
        fprintf(stderr, "usage: %s <refpack_out.txt>\n", argv[0]);
        return 1;
    }
    FILE *out = fopen(argv[1], "w");
    if (!out) {
        fprintf(stderr, "cannot open %s\n", argv[1]);
        return 1;
    }

    fprintf(out, "# RefPack golden vectors (parity level P0).\n");
    fprintf(out, "# Generated by tools/differential/gen_compress_golden.cpp, which\n");
    fprintf(out, "# compiles the REAL EAC codec sources (refdecode.cpp / refencode.cpp)\n");
    fprintf(out, "# from the baseline commit. Inputs are hex; '-' is the empty byte\n");
    fprintf(out, "# string. Regenerate with tools/differential/regenerate.sh.\n");

    // 1. Edge sizes around the encoder's 4-byte look-ahead margin.
    for (size_t len = 0; len <= 24; len++) {
        std::vector<uint8_t> input(len);
        for (size_t i = 0; i < len; i++)
            input[i] = (uint8_t)(i * 7 + 3);
        emit_round(out, input);
    }

    // 2. Structured, compressible data: repeated patterns with mutations
    //    (exercises the two/three/four byte match forms and the hash
    //    chains; includes matches beyond 1024 bytes).
    for (int round = 0; round < 40; round++) {
        std::vector<uint8_t> input;
        std::vector<uint8_t> pattern(1 + (lcg() % 64));
        for (auto &b : pattern)
            b = (uint8_t)(lcg() >> 24);
        int reps = 1 + (int)(lcg() % 300);
        for (int i = 0; i < reps; i++) {
            input.insert(input.end(), pattern.begin(), pattern.end());
            if (lcg() % 8 == 0 && !input.empty())
                input.back() = (uint8_t)(lcg() >> 24); // break a match
        }
        emit_round(out, input);
    }

    // 3. Incompressible random data (literal blocks + the long-literal
    //    0xe0 encoding) plus low-entropy runs (literal runs of 0..3 bytes
    //    between matches).
    for (int round = 0; round < 30; round++) {
        std::vector<uint8_t> input(200 + (lcg() % 3000));
        for (auto &b : input)
            b = (uint8_t)(lcg() >> 24);
        emit_round(out, input);
    }
    for (int round = 0; round < 20; round++) {
        std::vector<uint8_t> input(200 + (lcg() % 4000));
        for (auto &b : input)
            b = (uint8_t)((lcg() % 3) ? 0 : (lcg() >> 24));
        emit_round(out, input);
    }

    // 4. A big input crossing the 3-byte size header boundary and long
    //    matches (forces the 4-byte "very int" form and near-1028 matches).
    {
        std::vector<uint8_t> input(0x10000);
        for (size_t i = 0; i < input.size(); i++)
            input[i] = (uint8_t)((i % 700 < 300) ? 0x41 : (i * 5 >> 7));
        emit_round(out, input);
    }

    fclose(out);
    return 0;
}
