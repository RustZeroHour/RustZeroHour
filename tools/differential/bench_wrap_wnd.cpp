// The bench corpus repetition (12 two-window blocks ≈ 187 KiB, the scale
// of the other Phase 2 benches).
#define BENCH_WINDOWS 12

// The final-state checksum over the layout's observable fields (the same
// walk the Rust bench drives): the root count, every window's id, rect,
// status, style, first enabled draw color, enabled text color and
// tooltip delay, and the final default text color.
static uint64_t wnd_checksum(const LoadState &S)
{
        uint64_t sum = (uint64_t)S.roots.size();
        for (const GameWindow *w : S.arena) {
                sum = sum * 31 + (uint64_t)(uint32_t)w->inst.m_id;
                sum = sum * 31 + (uint64_t)(uint32_t)w->x;
                sum = sum * 31 + (uint64_t)(uint32_t)w->y;
                sum = sum * 31 + (uint64_t)(uint32_t)w->width;
                sum = sum * 31 + (uint64_t)(uint32_t)w->height;
                sum = sum * 31 + (uint64_t)w->inst.m_status;
                sum = sum * 31 + (uint64_t)w->inst.m_style;
                sum = sum * 31 + (uint64_t)w->inst.m_enabledDrawData[0].color;
                sum = sum * 31 + (uint64_t)w->inst.m_enabledText.color;
                sum = sum * 31 + (uint64_t)(uint32_t)w->inst.m_tooltipDelay;
        }
        sum = sum * 31 + (uint64_t)S.defTextColor;
        return sum;
}

// One nine-line draw-data stanza with the same formula values the Rust
// bench's stanza() writes (keep the two in lockstep).
static void bench_stanza(std::string &t, const char *token, uint32_t k)
{
        std::string pad(strlen(token), ' ');
        for (uint32_t i = 0; i < 9; i++) {
                char iname[64];
                snprintf(iname, sizeof(iname), "BImg%u", (i + k) % 7);
                const char *use_name = (i % 3 == 0) ? "NoImage" : iname;
                uint32_t rr = (k * 13 + i * 17) % 300;
                uint32_t gg = (k * 7 + i * 11) % 300;
                uint32_t bb = (k * 29 + i * 3) % 300;
                uint32_t a = 200 + ((k + i) % 56);
                uint32_t br = (k * 3 + i * 23) % 300;
                uint32_t bg = (k * 11 + i * 5) % 300;
                uint32_t bb2 = (k * 19 + i * 13) % 300;
                uint32_t ba = 150 + ((k * 2 + i) % 106);
                const char *tail = (i == 8) ? ";" : ",";
                char line[512];
                if (i == 0)
                        snprintf(line, sizeof(line),
                                 "%s = IMAGE: %s, COLOR: %u %u %u %u, BORDERCOLOR: %u %u %u %u%s\n",
                                 token, use_name, rr, gg, bb, a, br, bg, bb2, ba, tail);
                else
                        snprintf(line, sizeof(line),
                                 "             %s   IMAGE: %s, COLOR: %u %u %u %u, BORDERCOLOR: %u %u %u %u%s\n",
                                 pad.c_str(), use_name, rr, gg, bb, a, br, bg, bb2, ba, tail);
                t += line;
        }
}

// Builds the corpus: the same formula as the Rust bench's build_corpus()
// (keep the two in lockstep).
static std::string bench_corpus()
{
        std::string t = "FILE_VERSION = 2;\nSTARTLAYOUTBLOCK\n  LAYOUTINIT = BenchInit;\n  "
                        "LAYOUTUPDATE = BenchUpdate;\nENDLAYOUTBLOCK\n";
        char line[512];
        for (uint32_t i = 0; i < BENCH_WINDOWS; i++) {
                uint32_t x = (i * 7) % 400;
                uint32_t y = (i * 11) % 300;
                t += "WINDOW\nWINDOWTYPE = USER;\n";
                snprintf(line, sizeof(line),
                         "SCREENRECT = UPPERLEFT: %u %u,\n             BOTTOMRIGHT: %u %u,\n"
                         "             CREATIONRESOLUTION: 800 600;\n",
                         x, y, x + 120, y + 80);
                t += line;
                snprintf(line, sizeof(line), "NAME = \"Bench.wnd:Win%u\";\n", i);
                t += line;
                t += "STATUS = ENABLED+DRAGABLE+SEETHRU;\n";
                t += "STYLE = MOUSETRACK+ANIMATED;\n";
                snprintf(line, sizeof(line),
                         "SYSTEMCALLBACK = \"SysCB%u\";\nINPUTCALLBACK = \"InCB%u\";\n", i % 4,
                         i % 3);
                t += line;
                snprintf(line, sizeof(line),
                         "TOOLTIPCALLBACK = \"TipCB%u\";\nDRAWCALLBACK = \"DrawCB%u\";\n", i % 5,
                         i % 2);
                t += line;
                t += "FONT = NAME: \"Airborne\", SIZE: 12, BOLD: 0;\n";
                t += "HEADERTEMPLATE = \"BenchHeader\";\n";
                snprintf(line, sizeof(line), "TOOLTIPTEXT = \"Tip:%u\";\nTOOLTIPDELAY = %u ;\n",
                         i, i % 30);
                t += line;
                snprintf(line, sizeof(line), "TEXT = \"GUI:Item%u\";\n", i);
                t += line;
                t += "IMAGEOFFSET = 3 7;\n";
                uint32_t er = (i * 3) % 256, eg = (i * 5) % 256, eb = (i * 7) % 256;
                uint32_t dr = (i * 11) % 256, dg = (i * 13) % 256, db = (i * 17) % 256;
                uint32_t hr = (i * 19) % 256, hg = (i * 23) % 256, hb = (i * 29) % 256;
                snprintf(line, sizeof(line),
                         "TEXTCOLOR = ENABLED:  %u %u %u 255, ENABLEDBORDER:  0 0 0 255,\n"
                         "            DISABLED: %u %u %u 255, DISABLEDBORDER: 0 0 0 255,\n"
                         "            HILITE:   %u %u %u 255, HILITEBORDER:   64 64 64 255;\n",
                         er, eg, eb, dr, dg, db, hr, hg, hb);
                t += line;
                bench_stanza(t, "ENABLEDDRAWDATA", i);
                bench_stanza(t, "DISABLEDDRAWDATA", i + 1);
                bench_stanza(t, "HILITEDRAWDATA", i + 2);
                t += "CHILD\n";
                t += "WINDOW\nWINDOWTYPE = SCROLLLISTBOX;\n";
                snprintf(line, sizeof(line),
                         "SCREENRECT = UPPERLEFT: %u %u,\n             BOTTOMRIGHT: %u %u,\n"
                         "             CREATIONRESOLUTION: 800 600;\n",
                         x + 5, y + 5, x + 115, y + 75);
                t += line;
                snprintf(line, sizeof(line), "NAME = \"Bench.wnd:List%u\";\n", i);
                t += line;
                snprintf(line, sizeof(line),
                         "LISTBOXDATA = LENGTH: %u,\n              AUTOSCROLL: %u,\n              "
                         "AUTOPURGE: %u,\n              SCROLLBAR: 1,\n              "
                         "MULTISELECT: %u,\n              COLUMNS: 1,\n              "
                         "FORCESELECT: %u;\n",
                         i % 20, i % 2, (i + 1) % 2, (i % 3 == 0) ? 1 : 0, (i % 5 == 0) ? 1 : 0);
                t += line;
                bench_stanza(t, "LISTBOXENABLEDUPBUTTONDRAWDATA", i + 3);
                bench_stanza(t, "LISTBOXDISABLEDUPBUTTONDRAWDATA", i + 4);
                bench_stanza(t, "LISTBOXHILITEUPBUTTONDRAWDATA", i + 5);
                bench_stanza(t, "LISTBOXENABLEDDOWNBUTTONDRAWDATA", i + 6);
                bench_stanza(t, "LISTBOXDISABLEDDOWNBUTTONDRAWDATA", i + 7);
                bench_stanza(t, "LISTBOXHILITEDOWNBUTTONDRAWDATA", i + 8);
                bench_stanza(t, "LISTBOXENABLEDSLIDERDRAWDATA", i + 9);
                bench_stanza(t, "LISTBOXDISABLEDSLIDERDRAWDATA", i + 10);
                bench_stanza(t, "LISTBOXHILITESLIDERDRAWDATA", i + 11);
                bench_stanza(t, "SLIDERTHUMBENABLEDDRAWDATA", i + 12);
                bench_stanza(t, "SLIDERTHUMBDISABLEDDRAWDATA", i + 13);
                bench_stanza(t, "SLIDERTHUMBHILITEDRAWDATA", i + 14);
                t += "END\nENDALLCHILDREN\nEND\n";
        }
        return t;
}

extern "C" long bench_wnd_materialize(uint8_t *out, size_t cap);
extern "C" long bench_wnd_materialize(uint8_t *out, size_t cap)
{
        std::string t = bench_corpus();
        if (t.size() > cap)
                return -1;
        memcpy(out, t.data(), t.size());
        return (long)t.size();
}

extern "C" uint64_t bench_wnd_parse(const uint8_t *data, size_t len);
extern "C" uint64_t bench_wnd_parse(const uint8_t *data, size_t len)
{
        RamFile file(data, len);
        LoadState S(&file, 800, 600);
        g_state = &S;
        g_verdict.word.clear();
        try {
                winCreateFromScript(S);
        } catch (WalkStop &) {
        }
        g_state = nullptr;
        uint64_t sum = wnd_checksum(S);
        for (size_t i = 0; i < S.arena.size(); i++)
                delete S.arena[i];
        return sum;
}
