#!/bin/sh
# SPDX-License-Identifier: GPL-3.0-or-later
#
# Regenerates the rzh-util and rzh-math golden vectors from the C++ reference
# transcription. Requires a C++ compiler (g++ or clang++) on an IEEE-754
# platform (x86-64, arm64, ...).
#
# The gmath vectors additionally link the REAL pinned GameMath sources
# (TheSuperHackers/GameMath at 59f7ccd4, the pin cmake/gamemath.cmake
# fetches); the script clones the pin, so it needs network access the first
# time. Set GAMEMATH_DIR to reuse an existing checkout.
#
# Usage:
#   tools/differential/regenerate.sh
#
# After regenerating, run:
#   cargo test --workspace
# and review the git diff of crates/*/tests/golden before committing.

set -e

SCRIPT_DIR=$(CDPATH= cd -- "$(dirname -- "$0")" && pwd)
REPO_ROOT=$(CDPATH= cd -- "$SCRIPT_DIR/../.." && pwd)
UTIL_GOLDEN="$REPO_ROOT/crates/rzh-util/tests/golden"
MATH_GOLDEN="$REPO_ROOT/crates/rzh-math/tests/golden"

CXX=${CXX:-g++}
command -v "$CXX" >/dev/null 2>&1 || CXX=clang++
command -v "$CXX" >/dev/null 2>&1 || {
    echo "error: no C++ compiler found (tried g++ and clang++)" >&2
    exit 1
}
CC=${CC:-cc}

BUILD_DIR=$(mktemp -d)
GAMEMATH_DIR=${GAMEMATH_DIR:-$BUILD_DIR/gamemath}
trap 'rm -rf "$BUILD_DIR"' EXIT

# --- the pinned GameMath sources (needed by both generators) -------------
GAMEMATH_PIN=59f7ccd494f7e7c916a784ac26ef266f9f09d78d
if [ ! -d "$GAMEMATH_DIR/.git" ]; then
    echo "cloning GameMath pin $GAMEMATH_PIN ..."
    git clone -q https://github.com/TheSuperHackers/GameMath.git "$GAMEMATH_DIR"
    git -C "$GAMEMATH_DIR" checkout -q "$GAMEMATH_PIN"
fi
PIN_ACTUAL=$(git -C "$GAMEMATH_DIR" rev-parse HEAD)
if [ "$PIN_ACTUAL" != "$GAMEMATH_PIN" ]; then
    echo "error: $GAMEMATH_DIR is at $PIN_ACTUAL, expected $GAMEMATH_PIN" >&2
    exit 1
fi

# -ffp-contract=off: keep a*b+c as two IEEE operations. The C++ default for
# GCC/clang is "fast", which may fuse them into an FMA where the target
# supports it; Rust never contracts, and the game's MSVC build does not
# either (fp:precise). Without this flag the vector goldens would only be
# reproducible on baseline x86-64.
#
# gen_golden.cpp includes "gmath.h" and links the pin's float routines: the
# WWMath transcription's transcendental entry points must produce exactly
# what the game's deterministic build produces.
echo "compiling gen_golden.cpp with $CXX (linked against the pin)..."
PIN_SOURCES="$GAMEMATH_DIR/float/s_sinf.c $GAMEMATH_DIR/float/s_cosf.c \
    $GAMEMATH_DIR/float/s_tanf.c $GAMEMATH_DIR/float/k_sinf.c \
    $GAMEMATH_DIR/float/k_cosf.c $GAMEMATH_DIR/float/k_tanf.c \
    $GAMEMATH_DIR/float/k_rem_pio2f.c $GAMEMATH_DIR/float/e_asinf.c \
    $GAMEMATH_DIR/float/e_acosf.c $GAMEMATH_DIR/float/s_atanf.c \
    $GAMEMATH_DIR/float/e_atan2f.c $GAMEMATH_DIR/float/e_powf.c \
    $GAMEMATH_DIR/float/e_expf.c $GAMEMATH_DIR/float/e_logf.c \
    $GAMEMATH_DIR/float/e_log10f.c $GAMEMATH_DIR/float/e_sinhf.c \
    $GAMEMATH_DIR/float/e_coshf.c $GAMEMATH_DIR/float/s_tanhf.c \
    $GAMEMATH_DIR/float/s_expm1f.c $GAMEMATH_DIR/float/k_expf.c \
    $GAMEMATH_DIR/float/s_scalbnf.c $GAMEMATH_DIR/float/s_lrintf.c \
    $GAMEMATH_DIR/float/s_fabsf.c $GAMEMATH_DIR/float/s_floorf.c \
    $GAMEMATH_DIR/float/s_copysignf.c $GAMEMATH_DIR/float/e_sqrtf.c \
    $GAMEMATH_DIR/common/infinity.c"
PIN_CFLAGS="-ffp-contract=off -fno-builtin -fno-strict-aliasing -I$GAMEMATH_DIR/include -I$GAMEMATH_DIR/common -I$GAMEMATH_DIR/float"
# gen_golden.cpp itself is held to -Werror; the 1993-era msun sources are
# not (matching how GameMath's own CMake suppresses their warnings), so
# they are compiled to objects first without -Werror. They are C sources:
# compiled with the C compiler (C linkage) and BUILD_WITH_INTRINSICS, the
# same configuration the gmath generator below and the pin's own CMake
# use.
"$CXX" -O2 -std=c++17 -Wall -Wextra -Werror $PIN_CFLAGS \
    -c -o "$BUILD_DIR/gen_golden.o" "$SCRIPT_DIR/gen_golden.cpp"
for src in $PIN_SOURCES; do
    obj="$BUILD_DIR/$(basename "$src").o"
    "$CC" -O2 $PIN_CFLAGS -DBUILD_WITH_INTRINSICS -c -o "$obj" "$src"
done
"$CXX" -o "$BUILD_DIR/gen_golden" "$BUILD_DIR/gen_golden.o" "$BUILD_DIR"/*.c.o -lm

mkdir -p "$UTIL_GOLDEN" "$MATH_GOLDEN"
"$BUILD_DIR/gen_golden" \
    "$UTIL_GOLDEN/crc.txt" \
    "$UTIL_GOLDEN/rng.txt" \
    "$UTIL_GOLDEN/namekey.txt" \
    "$MATH_GOLDEN/scalar.txt" \
    "$MATH_GOLDEN/vectors.txt" \
    "$MATH_GOLDEN/matrices.txt" \
    "$MATH_GOLDEN/geometry.txt"

echo "wrote $UTIL_GOLDEN/{crc,rng,namekey}.txt"
echo "wrote $MATH_GOLDEN/{scalar,vectors,matrices,geometry}.txt"

# --- gmath golden vectors, generated by the pinned GameMath C sources ----

# The GameMath library's own build flags (CMakeLists.txt): no builtin math
# replacement, no strict aliasing assumptions. BUILD_WITH_INTRINSICS matches
# the game's build (GM_ENABLE_INTRINSICS defaults ON, gamemath.cmake only
# disables the tests). The 1993-era msun sources do not pass -Werror on
# modern compilers (misleading-indentation, sign-compare), so only the
# driver is held to that standard — matching how GameMath's own CMake
# suppresses its warnings.
echo "compiling gen_gmath_golden.c against the pin..."
PIN_FLAGS="-O2 -std=c99 -ffp-contract=off -fno-builtin -fno-strict-aliasing -DBUILD_WITH_INTRINSICS -I$GAMEMATH_DIR/include -I$GAMEMATH_DIR/common -I$GAMEMATH_DIR/float"
"$CC" $PIN_FLAGS -Wall -Wextra -Werror -c -o "$BUILD_DIR/gen_gmath_golden.o" \
    "$SCRIPT_DIR/gen_gmath_golden.c"
"$CC" $PIN_FLAGS -o "$BUILD_DIR/gen_gmath_golden" "$BUILD_DIR/gen_gmath_golden.o" \
    "$GAMEMATH_DIR/float/s_sinf.c" \
    "$GAMEMATH_DIR/float/s_cosf.c" \
    "$GAMEMATH_DIR/float/s_tanf.c" \
    "$GAMEMATH_DIR/float/k_sinf.c" \
    "$GAMEMATH_DIR/float/k_cosf.c" \
    "$GAMEMATH_DIR/float/k_tanf.c" \
    "$GAMEMATH_DIR/float/k_rem_pio2f.c" \
    "$GAMEMATH_DIR/float/e_asinf.c" \
    "$GAMEMATH_DIR/float/e_acosf.c" \
    "$GAMEMATH_DIR/float/s_atanf.c" \
    "$GAMEMATH_DIR/float/e_atan2f.c" \
    "$GAMEMATH_DIR/float/e_powf.c" \
    "$GAMEMATH_DIR/float/e_expf.c" \
    "$GAMEMATH_DIR/float/e_logf.c" \
    "$GAMEMATH_DIR/float/e_log10f.c" \
    "$GAMEMATH_DIR/float/e_sinhf.c" \
    "$GAMEMATH_DIR/float/e_coshf.c" \
    "$GAMEMATH_DIR/float/s_tanhf.c" \
    "$GAMEMATH_DIR/float/s_expm1f.c" \
    "$GAMEMATH_DIR/float/k_expf.c" \
    "$GAMEMATH_DIR/float/s_scalbnf.c" \
    "$GAMEMATH_DIR/float/s_lrintf.c" \
    "$GAMEMATH_DIR/float/s_fabsf.c" \
    "$GAMEMATH_DIR/float/s_floorf.c" \
    "$GAMEMATH_DIR/float/s_copysignf.c" \
    "$GAMEMATH_DIR/float/e_sqrtf.c" \
    "$GAMEMATH_DIR/common/infinity.c" \
    -lm

"$BUILD_DIR/gen_gmath_golden" "$MATH_GOLDEN/gmath.txt"
echo "wrote $MATH_GOLDEN/gmath.txt"

# --- refpack golden vectors, generated by the REAL EAC codec sources ----
# The 1995-era codec sources are compiled as their own translation units
# (like the game build) without -Werror; only the driver is held to it.
echo "compiling gen_compress_golden.cpp against the real codec sources..."
EAC_DIR="$REPO_ROOT/Core/Libraries/Source/Compression/EAC"
"$CXX" -O2 -std=c++17 -Wall -Wextra -Werror -ffp-contract=off \
    -I"$EAC_DIR" \
    -c -o "$BUILD_DIR/gen_compress_golden.o" "$SCRIPT_DIR/gen_compress_golden.cpp"
"$CXX" -O2 -ffp-contract=off -I"$EAC_DIR" \
    -c -o "$BUILD_DIR/refdecode.o" "$EAC_DIR/refdecode.cpp"
"$CXX" -O2 -ffp-contract=off -I"$EAC_DIR" \
    -c -o "$BUILD_DIR/refencode.o" "$EAC_DIR/refencode.cpp"
"$CXX" -o "$BUILD_DIR/gen_compress_golden" \
    "$BUILD_DIR/gen_compress_golden.o" "$BUILD_DIR/refdecode.o" "$BUILD_DIR/refencode.o"
mkdir -p "$REPO_ROOT/crates/rzh-compress/tests/golden"
"$BUILD_DIR/gen_compress_golden" "$REPO_ROOT/crates/rzh-compress/tests/golden/refpack.txt"
echo "wrote crates/rzh-compress/tests/golden/refpack.txt"

# --- vfs golden vectors: the archive/overlay logic transcribed, with the
# REAL EAC codec linked for every compressed payload. The generator owns a
# scratch directory for the local-file half of the scenario.
echo "compiling gen_vfs_golden.cpp against the real codec sources..."
"$CXX" -O2 -std=c++17 -Wall -Wextra -Werror -ffp-contract=off \
    -I"$EAC_DIR" \
    -c -o "$BUILD_DIR/gen_vfs_golden.o" "$SCRIPT_DIR/gen_vfs_golden.cpp"
"$CXX" -o "$BUILD_DIR/gen_vfs_golden" \
    "$BUILD_DIR/gen_vfs_golden.o" "$BUILD_DIR/refdecode.o" "$BUILD_DIR/refencode.o"
mkdir -p "$REPO_ROOT/crates/rzh-vfs/tests/golden"
"$BUILD_DIR/gen_vfs_golden" \
    "$REPO_ROOT/crates/rzh-vfs/tests/golden/vfs.txt" "$BUILD_DIR/vfs-scratch"
echo "wrote crates/rzh-vfs/tests/golden/vfs.txt"

# --- ini golden dump: the INI engine transcription (reader, tokenizer,
# scan functions, the three task-10 block schemas) replayed over the
# committed fixtures. The generator reads the fixtures relative to the
# repo root by default.
echo "compiling gen_ini_golden.cpp ..."
"$CXX" -O2 -std=c++17 -Wall -Wextra -Werror -ffp-contract=off \
    -c -o "$BUILD_DIR/gen_ini_golden.o" "$SCRIPT_DIR/gen_ini_golden.cpp"
"$CXX" -o "$BUILD_DIR/gen_ini_golden" "$BUILD_DIR/gen_ini_golden.o"
mkdir -p "$REPO_ROOT/crates/rzh-ini/tests/golden"
"$BUILD_DIR/gen_ini_golden" \
    "$REPO_ROOT/crates/rzh-ini/tests/golden/ini.txt" \
    "$REPO_ROOT/crates/rzh-ini/tests/fixtures"
echo "wrote crates/rzh-ini/tests/golden/ini.txt"

# --- csf golden dump: the Babylon writer transcription (expimp.cpp,
# minus its tool-only content transforms) plus the runtime reader
# transcription (GameText.cpp parseCSF + stripSpaces), over hand-crafted
# corpora and assembled edge-case blobs.
echo "compiling gen_csf_golden.cpp ..."
"$CXX" -O2 -std=c++17 -Wall -Wextra -Werror -ffp-contract=off \
    -c -o "$BUILD_DIR/gen_csf_golden.o" "$SCRIPT_DIR/gen_csf_golden.cpp"
"$CXX" -o "$BUILD_DIR/gen_csf_golden" "$BUILD_DIR/gen_csf_golden.o"
mkdir -p "$REPO_ROOT/crates/rzh-formats/tests/golden"
"$BUILD_DIR/gen_csf_golden" "$REPO_ROOT/crates/rzh-formats/tests/golden/csf.txt"
echo "wrote crates/rzh-formats/tests/golden/csf.txt"
echo "now run: cargo test --workspace"
