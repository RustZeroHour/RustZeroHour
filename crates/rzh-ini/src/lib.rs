//! The Zero Hour INI engine (migration plan task 10).
//!
//! Zero Hour is data-driven: nearly all game behaviour — objects,
//! weapons, armor, locomotors, special powers, … — is authored in INI
//! text and parsed once at load time by the `INI` reader
//! (`Core/GameEngine/Source/Common/INI/INI.cpp`). This crate is that
//! reader, ported with its exact semantics, plus the three validation
//! block types the migration plan's task 10 calls for:
//!
//! - [`blocks::armor`]: complete `Armor` templates;
//! - [`blocks::locomotor`]: complete `Locomotor` templates (every field
//!   of the original table, the constructor defaults and `validate`);
//! - [`blocks::weapon`]: a documented representative `Weapon` subset
//!   covering every generic parse procedure.
//!
//! # What is ported
//!
//! - the line reader's byte-level semantics (comments, control
//!   characters, the 1028-byte line cap, EOF edge cases);
//! - `strtok`-compatible tokenizing, including per-call separator sets;
//! - the `scanInt`/`scanUnsignedInt`/`scanReal`/… value scanners with
//!   their `std::from_chars`-plus-`strto*` overflow behaviour (the
//!   baseline builds with `USE_STD_FROM_CHARS_PARSING = 1`);
//! - the `initFromINI` field loop (case-sensitive field lookup,
//!   case-insensitive `End`, silent unknown-field skip of release
//!   builds, missing-`End` failure);
//! - the block dispatch of `INI::load` and the unit conversions of the
//!   generic parse procedures (durations, velocities, accelerations,
//!   angles at the 30 Hz logic-frame rate);
//! - the quoted-string readers with their historical quirks (the
//!   double-space glue of `getNextAsciiString`, the fixed
//!   `getNextQuotedAsciiString`).
//!
//! # What is not ported yet (and where it lands)
//!
//! - directory loads, load order, `#define`/include preprocessing and
//!   reskin handling → Phase 2 (`rzh-data` + `rzh-vfs` integration);
//! - the typed game-data field tables beyond the three validation
//!   blocks → Phase 2 (`rzh-data`);
//! - game-singleton field parsers (audio events, FX lists, particle
//!   systems, thing templates, sciences) → Phase 2, with their stores.
//!
//! # Parity level
//!
//! **P0 exact** (plan §3.2): the committed golden vectors in
//! `tests/golden/` are generated by the C++ transcription in
//! `tools/differential/gen_ini_golden.cpp` and compared byte-for-byte.
//! The scan functions additionally carry the upstream GoogleTest tables
//! from `Tests/Google/Core/GameEngine/Common/INITest.cpp` as unit tests.
//!
//! # Determinism
//!
//! `#![forbid(unsafe_code)]`; no global mutable state — the C++
//! singletons (`TheNameKeyGenerator`, the stores) became explicit
//! values owned by the caller; ordered maps only (plan §3.3).

#![forbid(unsafe_code)]

pub mod blocks;
pub mod error;
pub mod reader;
pub mod scan;

pub use error::{ErrorKind, IniError};
