    #[test]
    fn boxes_transform_consistently() {
        let mut m = Matrix3D::identity();
        m.rotate_z(0.6);
        m.translate(1.0, 2.0, 3.0);

        let min = Vector3::new(-1.0, -2.0, -3.0);
        let max = Vector3::new(1.0, 2.0, 3.0);
        let (bmin, bmax) = m.transform_min_max_aabox(min, max);
        // every transformed corner must lie inside the result
        for x in [min.x, max.x] {
            for y in [min.y, max.y] {
                for z in [min.z, max.z] {
                    let c = m.transform_vector(Vector3::new(x, y, z));
                    assert!(c.x >= bmin.x - 1e-5 && c.x <= bmax.x + 1e-5);
                    assert!(c.y >= bmin.y - 1e-5 && c.y <= bmax.y + 1e-5);
                    assert!(c.z >= bmin.z - 1e-5 && c.z <= bmax.z + 1e-5);
                }
            }
        }

        // center/extent form describes the same box
        let center = (min + max) * 0.5;
        let extent = (max - min) * 0.5;
        let (cc, ce) = m.transform_center_extent_aabox(center, extent);
        assert!(approx(cc.x, (bmin.x + bmax.x) * 0.5));
        assert!(approx(ce.x, (bmax.x - bmin.x) * 0.5));
        assert!(approx(cc.z, (bmin.z + bmax.z) * 0.5));
        assert!(approx(ce.z, (bmax.z - bmin.z) * 0.5));
    }

    #[test]
    fn solve_linear_system_finds_the_solution() {
        // x + y + z = 6; 2y + 5z = -4; 4x + 3z = 2. The 3x3 part ends
        // inverted like the C++; the ANSWER column carries the original's
        // Vector4::operator-= quirk (W added, not subtracted — see
        // `row_eliminate`), so the recorded answers are the engine's, not
        // the textbook (3, 19/3, -10/3). Values traced by hand against the
        // transcribed algorithm and pinned by the golden vectors.
        let mut system = Matrix3D::from_components(
            1.0, 1.0, 1.0, 6.0, //
            0.0, 2.0, 5.0, -4.0, //
            4.0, 0.0, 3.0, 2.0,
        );
        assert!(Matrix3D::solve_linear_system(&mut system));
        assert!(
            approx(system.rows[0].w, 155.0 / 9.0),
            "{}",
            system.rows[0].w
        );
        assert!(approx(system.rows[1].w, 67.0 / 9.0), "{}", system.rows[1].w);
        assert!(approx(system.rows[2].w, 34.0 / 9.0), "{}", system.rows[2].w);

        // the exact refusals: a zero pivot in the (0,0) slot
        let mut zero_pivot = Matrix3D::identity();
        zero_pivot.rows[0].x = 0.0;
        assert!(!Matrix3D::solve_linear_system(&mut zero_pivot));
    }

