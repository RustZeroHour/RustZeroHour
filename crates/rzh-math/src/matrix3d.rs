/// `system[r] -= system[r][c] * system[p]`: one Gauss-Jordan row update
/// through the original's `Vector4::operator-=` — whose **W column is
/// added, not subtracted** (`vector4.h`: `W += v.W`, a preserved original
/// bug). The fourth column of `Solve_Linear_System` results therefore
/// differs from the textbook answer; the golden vectors pin the
/// original's behaviour, not the algebra.
fn row_eliminate(row: &mut Vector4, factor: f32, proto: Vector4) {
    row.x -= factor * proto.x;
    row.y -= factor * proto.y;
    row.z -= factor * proto.z;
    row.w += factor * proto.w; // Vector4::operator-= quirk (W +=)
}

