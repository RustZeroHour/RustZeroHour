//! `gm_scalbnf`: scalbn(x, n) — x times 2^n, by exponent word surgery.
//!
//! Needed by `__kernel_rem_pio2f` (argument reduction) and `__ieee754_powf`.
//!
//! # Clippy
//!
//! `eq_op` and `excessive_precision` fires on the verbatim C literals and
//! on purpose-written `x - x` overflow sentinels; both are behaviour.
//!
//! # Parity level
//!
//! **P0 exact**: pinned by the golden vectors in `tests/golden/gmath.txt`,
//! generated by compiling the pinned C sources themselves
//! (`tools/differential/gen_gmath_golden.c`).

// Clippy notes for this verbatim msun transcription:
// - `excessive_precision` / `approx_constant`: the float literals keep the
//   exact decimal forms of the C sources (several approximate pi/e by
//   design); rounding them to fewer digits changes bits.
// - `eq_op`: NaN/overflow sentinels written as `x - x` / `(x-x)/(x-x)` in
//   the original are behaviour.
#![allow(clippy::excessive_precision, clippy::approx_constant, clippy::eq_op)]

/// `two25` = 2^25, the subnormal scaling factor.
const TWO25: f32 = 3.355_443_2e7; // 0x4c000000

/// `twom25` = 2^-25.
const TWOM25: f32 = 2.980_232_238_8e-8; // 0x33000000

const HUGE: f32 = 1.0e30;
const TINY: f32 = 1.0e-30;

/// `gm_scalbnf` (and its alias `gm_ldexpf`): returns `x * 2^n`.
///
/// Transcribed verbatim from `float/s_scalbnf.c`. The bit-twiddling uses the
/// float word as `i32` exactly like the C macro pair; the additions wrap in
/// C in practice (two's complement) and are transcribed with
/// [`wrapping_add`](i32::wrapping_add).
///
/// `gm_floorf` / `gm_copysignf` calls map onto `f32::floor` /
/// `f32::copysign`: both are IEEE-754 exact, bit-identical to the msun
/// versions (ADR-001, 0 mismatches over 40K+ inputs).
#[must_use]
pub fn scalbnf(x: f32, n: i32) -> f32 {
    let mut x = x;
    let mut ix = x.to_bits() as i32;
    let mut k = (ix & 0x7f80_0000) >> 23; // extract exponent

    if k == 0 {
        // 0 or subnormal x
        if (ix & 0x7fff_ffff) == 0 {
            return x; // +-0
        }
        x *= TWO25;
        ix = x.to_bits() as i32;
        k = ((ix & 0x7f80_0000) >> 23) - 25;
        if n < -50_000 {
            return TINY * x; // underflow
        }
    }
    if k == 0xff {
        return x + x; // NaN or Inf
    }
    k += n;
    if k > 0xfe {
        return HUGE * f32::copysign(HUGE, x); // overflow
    }
    if k > 0 {
        // normal result
        ix = (((ix as u32) & 0x807f_ffff) | ((k as u32) << 23)) as i32;
        return f32::from_bits(ix as u32);
    }
    if k <= -25 {
        if n > 50_000 {
            // in case integer overflow in n+k
            return HUGE * f32::copysign(HUGE, x); // overflow
        }
        return TINY * f32::copysign(TINY, x); // underflow
    }
    k += 25; // subnormal result
    ix = (((ix as u32) & 0x807f_ffff) | ((k as u32) << 23)) as i32;
    x = f32::from_bits(ix as u32);
    x * TWOM25
}
