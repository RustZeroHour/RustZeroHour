//! The GameMath (FreeBSD **msun**) float entry points — ADR-001 option C.
//!
//! The C++ side builds with `USE_DETERMINISTIC_MATH = 1` (the
//! retail-compatible build disables it; ADR-000 dropped retail
//! compatibility, so the port follows the deterministic path). Under that
//! switch, `WWMath`'s float transcendental entry points call the
//! **GameMath** library — the FreeBSD msun float routines vendored at pin
//! `59f7ccd494f7e7c916a784ac26ef266f9f09d78d` via `cmake/gamemath.cmake`
//! — instead of the platform libm.
//!
//! This module is a direct, line-for-line transcription of the pinned
//! msun float sources that the game actually reaches. The Rust `libm`
//! crate is a *different* msun descendant and is **not** bit-identical to
//! this pin (see ADR-001 for the mismatch measurements); it must not be
//! used in parity-sensitive code.
//!
//! # What is ported
//!
//! | Rust | msun source | reached from |
//! |------|-------------|--------------|
//! | [`sinf`] | `s_sinf.c` (+ `k_sinf.c`, `e_rem_pio2f.c`, `k_rem_pio2f.c`) | `WWMath::Sinf`, `Lib::Sin` |
//! | [`cosf`] | `s_cosf.c` (+ `k_cosf.c`, reduction chain) | `WWMath::Cosf`, `Lib::Cos` |
//! | [`tanf`] | `s_tanf.c` (+ `k_tanf.c`, reduction chain) | `WWMath::Tanf`, `Lib::Tan` |
//! | [`asinf`] | `e_asinf.c` | `WWMath::Asinf`, `Lib::ASin` |
//! | [`acosf`] | `e_acosf.c` | `WWMath::Acosf`, `Lib::ACos` |
//! | [`atanf`] | `s_atanf.c` | `WWMath::Atanf` |
//! | [`atan2f`] | `e_atan2f.c` | `WWMath::Atan2f` |
//! | [`powf`] | `e_powf.c` | `WWMath::Powf` / `Pow` |
//! | [`expf`] | `e_expf.c` | `WWMath::Expf` / `Exp` |
//! | [`expm1f`] | `s_expm1f.c` | hyperbolic chain |
//! | [`logf`] | `e_logf.c` | `WWMath::Logf` / `Log` |
//! | [`log10f`] | `e_log10f.c` (+ `k_logf.h`) | `WWMath::Log10f` / `Log10` |
//! | [`sinhf`] | `e_sinhf.c` | `WWMath::Sinhf` |
//! | [`coshf`] | `e_coshf.c` (+ `k_expf.c`) | `WWMath::Coshf` |
//! | [`tanhf`] | `s_tanhf.c` | `WWMath::Tanhf` |
//! | [`scalbnf`] | `s_scalbnf.c` | reduction chain, `powf` |
//! | [`rintf`], [`lrintf`] | `s_rintf.c`, `s_lrintf.c` | `WWMath::Float_To_Long` |
//!
//! `gm_sqrtf`, `gm_fabsf`, `gm_floorf`, `gm_ceilf`, `gm_copysignf` are
//! IEEE-754 exact and already live in [`crate::scalar`] mapped onto the
//! Rust std methods (ADR-001 verified bit-equality against the pin); the
//! kernels here call those exact equivalents.
//!
//! # Transcription conventions
//!
//! - Float words are handled as `i32`/`u32` exactly like the C
//!   `GET_FLOAT_WORD`/`SET_FLOAT_WORD` macros (`f32::to_bits` /
//!   `f32::from_bits`, no `unsafe`).
//! - C signed word arithmetic that wraps in practice on two's-complement
//!   machines uses [`wrapping_add`](i32::wrapping_add) and friends.
//! - `cliptofloat` (a volatile trick to clip x87 excess precision) is the
//!   identity: Rust evaluates floats at their natural width on every
//!   supported target.
//! - C float↔int casts truncate toward zero, matching Rust's `as` casts;
//!   every cast site in the algorithms is range-guarded.
//! - The one `goto` (`k_rem_pio2f`'s `recompute`) becomes a `loop`.
//!
//! # Parity level
//!
//! **P0 exact** for every entry point: the golden vectors in
//! `tests/golden/gmath.txt` are generated by compiling the *pinned C
//! sources themselves* (`tools/differential/gen_gmath_golden.c` linked
//! against the pin at `59f7ccd4`), not a re-transcription — the strongest
//! form of the differential check (plan §3.2).

