#[cfg(test)]
mod tests {
    use super::*;

    fn bits(x: f32) -> u32 {
        x.to_bits()
    }

    /// Sanity anchors — the real proof is the golden vector suite; these
    /// pin the handful of special cases the intrinsics/UB corners of C
    /// cannot exercise there.
    #[test]
    fn special_values() {
        // sin/cos of exact multiples of pi/2 reduced through the medium
        // path; values cross-checked against the pin output.
        assert_eq!(bits(sinf(0.0)), bits(0.0));
        assert_eq!(bits(cosf(0.0)), bits(1.0));
        // domain errors produce NaN
        assert!(asinf(2.0).is_nan());
        assert!(acosf(-1.5).is_nan());
        // signs (sinf preserves -0)
        assert_eq!(bits(sinf(-0.0f32)), bits(-0.0));
        // tanf(-0.0) is +0.0 in the pinned msun (r + T[0]*s sign
        // cancellation) — one of the ADR-001 divergences from the libm
        // crate; pinned as behaviour.
        assert_eq!(bits(tanf(-0.0f32)), bits(0.0));
        // lrintf intrinsic semantics: NaN/overflow -> i64::MIN
        assert_eq!(lrintf(f32::NAN), i64::MIN);
        assert_eq!(lrintf(f32::INFINITY), i64::MIN);
        assert_eq!(lrintf(-f32::INFINITY), i64::MIN);
        assert_eq!(lrintf(1.0e30), i64::MIN);
        // ties to even
        assert_eq!(lrintf(0.5), 0);
        assert_eq!(lrintf(1.5), 2);
        assert_eq!(lrintf(2.5), 2);
        assert_eq!(lrintf(-0.5), 0);
        assert_eq!(lrintf(-2.5), -2);
        // sqrtf/floorf mapping sanity (via asinf/acosf paths)
        assert_eq!(bits(acosf(1.0)), bits(0.0));
        assert_eq!(bits(acosf(-1.0)), bits(acosf(-1.0)));
    }

    #[test]
    fn monotonic_sweep_matches_expectations() {
        // A coarse sweep must stay within [-1, 1]; gross errors (wrong
        // reduction, swapped kernels) fail this before the goldens run.
        let mut i = -4000;
        while i <= 4000 {
            let x = i as f32 * 0.001;
            let s = sinf(x);
            let c = cosf(x);
            assert!(s.abs() <= 1.000_000_1, "sin({x}) out of range: {s}");
            assert!(c.abs() <= 1.000_000_1, "cos({x}) out of range: {c}");
            // sin^2 + cos^2 ~ 1
            let d = (s * s + c * c - 1.0).abs();
            assert!(d < 1.0e-5, "identity broken at {x}: {d}");
            i += 7;
        }
    }
}
