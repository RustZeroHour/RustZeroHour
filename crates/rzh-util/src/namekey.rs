//! Name-key interning: translate between names and unique integer keys.
//!
//! Zero Hour converts arbitrary names (object template names, INI block
//! names, file paths, …) into unique 24-bit "name keys" once, then passes the
//! cheap keys around instead of comparing strings. The conversion must be
//! stable within one process and identical on every lockstep client, because
//! several stores (science store, upgrade center) identity their entries by
//! the key *value*.
//!
//! The C++ implementation is the `TheNameKeyGenerator` singleton; per the
//! migration plan's rule "no global mutable state" (plan §3.3 rule 5), this
//! port is an explicit [`NameKeyGenerator`] value owned by its context (the
//! data layer during load, later the simulation context). Create one, share
//! it by `&mut`, and keep the interning *order* deterministic across clients
//! — key values are assigned sequentially in first-seen order.
//!
//! # Parity level
//!
//! **P0 exact** (plan §3.2): the name → key mapping, the hash functions and
//! the reverse lookup produce byte-exact results for identical call
//! sequences. Enforced by the committed golden vectors in `tests/golden/`,
//! generated by the C++ transcription in `tools/differential/`.
//!
//! # Differences from the original, by design
//!
//! - Names are byte strings (`&[u8]`, anything `AsRef<[u8]>`) instead of
//!   `AsciiString`: the original compares raw bytes and its `tolower` folds
//!   ASCII only, so byte semantics is the faithful choice.
//! - [`NameKeyGenerator::key_to_name`] returns `None` for unknown keys where
//!   the C++ returns the empty string; callers use `unwrap_or(b"")` for the
//!   same behaviour. It runs in O(1) via the bucket arena instead of the
//!   original's linear scan (keys are unique, so the result is identical).
//! - `StaticNameKey` (a lazy memoizing lookup through the singleton) is not
//!   ported: it exists only to feed the C++ global. Rust code resolves names
//!   eagerly into its context during load.
//! - Allocating a key beyond [`NameKey::MAX_ORDINAL`] panics with a clear
//!   message. The C++ comment documents that keys "fit into 24 bits safely"
//!   but never enforces it; a silent overflow would corrupt every dependent
//!   store, so the port makes the invariant loud.
//!
//! # Examples
//!
//! ```
//! use rzh_util::namekey::NameKeyGenerator;
//!
//! let mut keys = NameKeyGenerator::new();
//!
//! // Keys are assigned sequentially from 1 in first-seen order.
//! let tank = keys.name_to_key("AmericaTank");
//! assert_eq!(tank.ordinal(), 1);
//!
//! // Interning the same name returns the same key without growing.
//! assert_eq!(keys.name_to_key("AmericaTank"), tank);
//!
//! // Case-sensitive lookups differ; case-insensitive ones canonicalize.
//! let gla = keys.name_to_lowercase_key("GLATank");
//! assert_eq!(keys.name_to_lowercase_key("glatank"), gla);
//! assert_eq!(keys.key_to_name(gla), Some(&b"glatank"[..]));
//! ```

use std::boxed::Box;
use std::vec::Vec;

/// The socket (bucket) count of the original hash table.
///
/// Ported verbatim: "socketcount should be prime, and not 'close' to a power
/// of 2, for best results."
pub const SOCKET_COUNT: u32 = 45_007;

/// Sentinel for "no bucket" in the socket heads and `next_in_socket` links.
const NO_BUCKET: u32 = u32::MAX;

/// A unique id for an interned name (`NameKeyType` in the original).
///
/// The value 0 ([`NameKey::INVALID`]) never names anything; every other
/// value is dynamically determined at runtime by a [`NameKeyGenerator`],
/// which hands out consecutive ordinals from 1. Some code relies on keys
/// fitting into 24 bits, hence [`NameKey::MAX_ORDINAL`].
#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Hash)]
pub struct NameKey(u32);

impl NameKey {
    /// The `NAMEKEY_INVALID` value: never allocated, means "no key".
    pub const INVALID: NameKey = NameKey(0);

    /// `NAMEKEY_MAX`: the maximum ordinal a key may have (fits in 24 bits).
    pub const MAX_ORDINAL: u32 = 1 << 23;

    /// Wraps an ordinal that came from a generator (or a save file).
    ///
    /// Values above [`NameKey::MAX_ORDINAL`] cannot have been produced by a
    /// generator; they are rejected here so malformed input fails early
    /// instead of poisoning lookups.
    ///
    /// # Panics
    ///
    /// Panics if `ordinal` exceeds [`NameKey::MAX_ORDINAL`].
    #[must_use]
    #[track_caller]
    pub const fn from_ordinal(ordinal: u32) -> Self {
        if ordinal > Self::MAX_ORDINAL {
            panic!("name key ordinal exceeds NAMEKEY_MAX (1 << 23)");
        }
        Self(ordinal)
    }

    /// The ordinal value (`0` for [`NameKey::INVALID`]).
    #[must_use]
    pub const fn ordinal(self) -> u32 {
        self.0
    }

    /// Whether this key names an interned name (`NAMEKEY_INVALID` does not).
    #[must_use]
    pub const fn is_valid(self) -> bool {
        self.0 != 0
    }
}

/// `calcHashForString`: the `hash * 33 + byte` shift-add hash over raw bytes.
///
/// Ported from `NameKeyGenerator.cpp`; the unsigned 32-bit wrap-around of
/// the original is preserved by `wrapping` operations. Public so the golden
/// vectors can verify it directly.
#[must_use]
pub fn calc_hash_for_string(name: &[u8]) -> u32 {
    let mut result: u32 = 0;
    for &byte in name {
        result = (result << 5)
            .wrapping_add(result)
            .wrapping_add(u32::from(byte));
    }
    result
}

/// `calcHashForLowercaseString`: [`calc_hash_for_string`] over ASCII-lowered
/// bytes.
///
/// The original applies C `tolower` to every byte: in the "C" locale this
/// folds only `A`-`Z` and leaves every other byte (including `128..=255`)
/// unchanged, which is exactly [`u8::to_ascii_lowercase`].
#[must_use]
pub fn calc_hash_for_lowercase_string(name: &[u8]) -> u32 {
    let mut result: u32 = 0;
    for &byte in name {
        let lowered = byte.to_ascii_lowercase();
        result = (result << 5)
            .wrapping_add(result)
            .wrapping_add(u32::from(lowered));
    }
    result
}

/// One entry of the intern table (`Bucket` in the original).
///
/// The key value is implicit: bucket `i` in the arena carries the key
/// `i + 1`, because the original assigns consecutive ids while appending.
#[derive(Debug)]
struct Bucket {
    /// Next bucket in the same socket, or [`NO_BUCKET`].
    next_in_socket: u32,
    /// The canonical stored name (lowercased for case-insensitive keys).
    name: Box<[u8]>,
}

/// Interns names into unique [`NameKey`]s (`NameKeyGenerator` subsystem).
///
/// Calling [`name_to_key`](Self::name_to_key) with the same name is
/// guaranteed to return the same key, and all keys of one generator are
/// unique with respect to its catalog of names. Multiple generators can be
/// created to service multiple namespaces (the original supported this but
/// shipped one global, `TheNameKeyGenerator`).
///
/// Keys depend on interning *order*: two lockstep clients must feed the same
/// names through their generators in the same order (they do, because data
/// loading is deterministic).
#[derive(Debug)]
pub struct NameKeyGenerator {
    /// Socket heads: index of the first bucket per socket, or [`NO_BUCKET`].
    sockets: Box<[u32]>,
    /// The bucket arena; bucket `i` carries key `i + 1`.
    buckets: Vec<Bucket>,
}

impl NameKeyGenerator {
    /// A fresh, empty generator (`init()` in the original; keys start at 1).
    #[must_use]
    pub fn new() -> Self {
        Self {
            sockets: vec![NO_BUCKET; SOCKET_COUNT as usize].into_boxed_slice(),
            buckets: Vec::new(),
        }
    }

    /// Empties the catalog and restarts key assignment at 1 (`reset()`).
    pub fn reset(&mut self) {
        self.sockets.fill(NO_BUCKET);
        self.buckets.clear();
    }

    /// Number of interned names; the next key handed out is `len() + 1`.
    #[must_use]
    pub fn len(&self) -> usize {
        self.buckets.len()
    }

    /// Whether no name has been interned yet.
    #[must_use]
    pub fn is_empty(&self) -> bool {
        self.buckets.is_empty()
    }

    /// `nameToKey`: interns `name` case-sensitively and returns its key.
    ///
    /// If an equal name (byte equality, like `strcmp`/`AsciiString::compare`)
    /// is already cataloged, its key is returned; otherwise a new key is
    /// allocated and the name is stored verbatim.
    pub fn name_to_key(&mut self, name: impl AsRef<[u8]>) -> NameKey {
        let name = name.as_ref();
        let socket = calc_hash_for_string(name) % SOCKET_COUNT;
        if let Some(key) = self.find_in_socket(socket, |stored| stored == name) {
            return key;
        }
        self.create_name_key(socket, name)
    }

    /// `nameToLowercaseKey`: interns `name` case-insensitively.
    ///
    /// The lookup compares ASCII-case-insensitively (like `_stricmp` in the
    /// "C" locale). A miss stores the **canonical lowercase** form of the
    /// name, so a later case-sensitive [`name_to_key`](Self::name_to_key)
    /// with the lowercase spelling reuses this key (upstream fix of
    /// 08/08/2026, included in the baseline).
    pub fn name_to_lowercase_key(&mut self, name: impl AsRef<[u8]>) -> NameKey {
        let name = name.as_ref();
        let socket = calc_hash_for_lowercase_string(name) % SOCKET_COUNT;
        if let Some(key) = self.find_in_socket(socket, |stored| stored.eq_ignore_ascii_case(name)) {
            return key;
        }
        let lowered = name.to_ascii_lowercase().into_boxed_slice();
        self.create_name_key(socket, &lowered)
    }

    /// `keyToName`: the canonical stored name for a key.
    ///
    /// Returns `None` for [`NameKey::INVALID`] and unknown keys (the
    /// original returns the empty string for both). Unlike the original's
    /// linear scan this is a direct index; keys are unique, so the answer is
    /// identical.
    #[must_use]
    pub fn key_to_name(&self, key: NameKey) -> Option<&[u8]> {
        let index = key.ordinal().checked_sub(1)?;
        self.buckets
            .get(index as usize)
            .map(|bucket| &bucket.name[..])
    }

    /// Walks one socket's chain and returns the key of the first bucket
    /// whose stored name satisfies `matches`.
    fn find_in_socket(&self, socket: u32, matches: impl Fn(&[u8]) -> bool) -> Option<NameKey> {
        let mut index = self.sockets[socket as usize];
        while index != NO_BUCKET {
            let bucket = &self.buckets[index as usize];
            if matches(&bucket.name) {
                return Some(NameKey::from_ordinal(index + 1));
            }
            index = bucket.next_in_socket;
        }
        None
    }

    /// `createNameKey`: appends a bucket at the head of its socket.
    ///
    /// The new key is `buckets.len() + 1` before pushing, which equals the
    /// original's `m_nextID` (it starts at 1 after `init`/`reset` and grows
    /// by one per created bucket).
    fn create_name_key(&mut self, socket: u32, name: &[u8]) -> NameKey {
        let next_id = self
            .buckets
            .len()
            .checked_add(1)
            .and_then(|len| u32::try_from(len).ok())
            .unwrap_or(0);
        assert!(
            next_id != 0 && next_id <= NameKey::MAX_ORDINAL,
            "name key space exhausted: more than {} interned names (NAMEKEY_MAX)",
            NameKey::MAX_ORDINAL
        );
        self.buckets.push(Bucket {
            next_in_socket: self.sockets[socket as usize],
            name: name.to_vec().into_boxed_slice(),
        });
        self.sockets[socket as usize] = next_id - 1;
        NameKey(next_id)
    }
}

impl Default for NameKeyGenerator {
    /// Same as [`NameKeyGenerator::new`].
    fn default() -> Self {
        Self::new()
    }
}

#[cfg(test)]
mod tests {
    use super::{NameKey, NameKeyGenerator, calc_hash_for_lowercase_string, calc_hash_for_string};

    #[test]
    fn hash_is_shift_add_times_33() {
        // "djb2"-family: result = result * 33 + byte (mod 2^32), start 0.
        let mut expected: u32 = 0;
        for &byte in b"AmericaTank" {
            expected = expected.wrapping_mul(33).wrapping_add(u32::from(byte));
        }
        assert_eq!(calc_hash_for_string(b"AmericaTank"), expected);
        assert_eq!(calc_hash_for_string(b""), 0);
    }

    #[test]
    fn lowercase_hash_folds_ascii_only() {
        assert_eq!(
            calc_hash_for_lowercase_string(b"AbC"),
            calc_hash_for_lowercase_string(b"abc")
        );
        assert_eq!(
            calc_hash_for_lowercase_string(b"ABC"),
            calc_hash_for_string(b"abc")
        );
        // High-bit bytes pass through untouched, like C `tolower` in the
        // "C" locale.
        assert_eq!(
            calc_hash_for_lowercase_string(&[0xC4, 0xDF]),
            calc_hash_for_string(&[0xC4, 0xDF])
        );
    }

    #[test]
    fn first_keys_are_sequential_from_one() {
        let mut keys = NameKeyGenerator::new();
        assert!(keys.is_empty());
        assert_eq!(keys.name_to_key("Alpha").ordinal(), 1);
        assert_eq!(keys.name_to_key("Beta").ordinal(), 2);
        assert_eq!(keys.name_to_key("Gamma").ordinal(), 3);
        assert_eq!(keys.len(), 3);
    }

    #[test]
    fn interning_is_stable_and_case_sensitive() {
        let mut keys = NameKeyGenerator::new();
        let first = keys.name_to_key("Foo");
        let second = keys.name_to_key("Foo");
        assert_eq!(first, second);
        assert_eq!(keys.len(), 1);

        let lower = keys.name_to_key("foo");
        assert_ne!(first, lower);
        assert_eq!(keys.len(), 2);
    }

    #[test]
    fn lowercase_keys_canonicalize_to_the_lowercased_name() {
        let mut keys = NameKeyGenerator::new();
        let mixed = keys.name_to_lowercase_key("MixedCase");
        assert_eq!(keys.name_to_lowercase_key("MIXEDCASE"), mixed);
        assert_eq!(keys.name_to_lowercase_key("mixedcase"), mixed);
        // The upstream fix: the canonical lowercase spelling is stored, so
        // the case-sensitive lookup of that spelling reuses the key.
        assert_eq!(keys.name_to_key("mixedcase"), mixed);
        assert_eq!(keys.key_to_name(mixed), Some(&b"mixedcase"[..]));
        assert_eq!(keys.len(), 1);
    }

    #[test]
    fn empty_and_high_bit_names_intern_like_anything_else() {
        let mut keys = NameKeyGenerator::new();
        let empty = keys.name_to_key("");
        assert_eq!(empty.ordinal(), 1);
        assert_eq!(keys.key_to_name(empty), Some(&b""[..]));

        let raw = keys.name_to_lowercase_key([0x41, 0xC4, 0xB0]);
        assert_eq!(keys.key_to_name(raw), Some(&[0x61, 0xC4, 0xB0][..]));
    }

    #[test]
    fn key_to_name_rejects_invalid_and_unknown_keys() {
        let mut keys = NameKeyGenerator::new();
        keys.name_to_key("Solo");
        assert_eq!(keys.key_to_name(NameKey::INVALID), None);
        assert_eq!(keys.key_to_name(NameKey::from_ordinal(99)), None);
        assert_eq!(
            keys.key_to_name(NameKey::from_ordinal(1)),
            Some(&b"Solo"[..])
        );
    }

    #[test]
    fn reset_restarts_the_catalog() {
        let mut keys = NameKeyGenerator::new();
        let first = keys.name_to_key("Name");
        keys.name_to_lowercase_key("Other");
        keys.reset();
        assert!(keys.is_empty());
        assert_eq!(keys.key_to_name(first), None);
        assert_eq!(keys.name_to_key("Name").ordinal(), 1);
    }

    #[test]
    fn separate_generators_are_separate_namespaces() {
        let mut a = NameKeyGenerator::new();
        let mut b = NameKeyGenerator::new();
        let ka = a.name_to_key("Same");
        let kb = b.name_to_lowercase_key("Same");
        // Same ordinal by coincidence of order, but independent catalogs.
        assert_eq!(ka.ordinal(), kb.ordinal());
        assert_eq!(a.key_to_name(ka), Some(&b"Same"[..]));
        assert_eq!(b.key_to_name(kb), Some(&b"same"[..]));
    }

    #[test]
    fn many_names_do_not_collision_confuse() {
        // A few thousand interned names exercise the socket chains; every
        // lookup must still return the exact key that created it.
        let mut keys = NameKeyGenerator::new();
        let mut expected = Vec::new();
        for i in 0..2000_u32 {
            let name = format!("Template{i}");
            expected.push((name.clone(), keys.name_to_key(&name)));
        }
        assert_eq!(keys.len(), expected.len());
        for (name, key) in &expected {
            assert_eq!(keys.name_to_key(name), *key);
            assert_eq!(keys.key_to_name(*key), Some(name.as_bytes()));
        }
    }
}
