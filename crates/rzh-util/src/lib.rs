//! Shared utilities for the RustZeroHour engine.
//!
//! This crate is the first foundation crate of the Rust migration
//! (docs/RUST_MIGRATION_PLAN.md, Phase 1). It ports the two leaf algorithms
//! that everything else in the engine depends on, byte-for-byte:
//!
//! - [`Crc`]: the game's custom 32-bit shift-add checksum
//!   (`CRC` in `Core/GameEngine/Include/Common/crc.h` and
//!   `Core/GameEngine/Source/Common/crc.cpp`).
//! - [`GameRng`]: the game's additive-feedback pseudo random number
//!   generator used by the logic, client and audio streams
//!   (`Core/GameEngine/Source/Common/RandomValue.cpp`).
//!
//! # Porting provenance
//!
//! Both modules are ported from baseline commit `571a7c5`, Zero Hour
//! configuration, following the **non-retail** branches of the
//! `RETAIL_COMPATIBLE_CRC` switches (see ADR-000). Each module header records
//! its exact origin.
//!
//! # Parity level
//!
//! Both algorithms are **P0 exact** (byte-exact outputs on identical inputs)
//! per the plan's §3.2. Parity is enforced by the committed golden vectors in
//! `tests/golden/`, which are generated by the C++ reference harness in
//! `tools/differential/` — rerun `tools/differential/regenerate.sh` to refresh
//! them.
//!
//! # Determinism rules honoured
//!
//! - `#![forbid(unsafe_code)]` (plan §3.3 rule 4).
//! - No global mutable state: the C++ global seed arrays become explicit
//!   [`GameRng`] values owned by their context (plan §3.3 rule 5).
//! - Fixed-width integer types (`u32`, `i32`) only; no `usize` in the API
//!   (plan §3.3 rule 6).
//! - `f32` arithmetic with the original operation order (plan §3.3 rule 6).

#![forbid(unsafe_code)]

pub mod crc;
pub mod rng;

pub use crc::Crc;
pub use rng::GameRng;
