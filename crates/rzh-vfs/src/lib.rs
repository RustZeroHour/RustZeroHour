//! The Zero Hour virtual file system for RustZeroHour.
//!
//! Phase 1 crate of the Rust migration plan (§3.4): the layer every
//! later data crate reads through —
//!
//! - [`Vfs`]: the overlay (`FileSystem.cpp`): loose files first, then
//!   BIG archives, with the instance routing that lets mods shadow the
//!   base game and lets callers reach behind a shadowing file;
//! - [`big`]: the BIG archive format (`BIGF` header, big-endian entry
//!   table, per-archive directory tree);
//! - [`archive_fs`]: the cross-archive overlay tree and file instances
//!   (`ArchiveFileSystem`);
//! - [`local`]: the loose-file layer (`Win32LocalFileSystem` behaviour
//!   on `std::fs`);
//! - [`ramfile`], [`big::StreamingFile`]: the two archive open modes
//!   (`RAMFile` / `StreamingArchiveFile`);
//! - [`compression`]: the `EAR\0` payload dispatch (`CompressionManager`),
//!   decoding through the byte-exact `rzh-compress` RefPack port;
//! - [`path`]: path keys and the ordered `FilenameList`;
//! - [`wildcard`]: the `*`/`?` matcher behind every enumeration.
//!
//! # Porting provenance
//!
//! Every module is ported from baseline commit `571a7c5`, Zero Hour
//! configuration, non-retail branches, and records its exact origin in
//! its header. EA's and TheSuperHackers' copyright notices are kept.
//!
//! # Parity level
//!
//! **P0 exact** (byte-level) for the whole crate: the golden vectors in
//! `tests/golden/vfs.txt` are generated by
//! `tools/differential/gen_vfs_golden.cpp` — a verbatim C++ transcription
//! of the engine's archive logic linked against the REAL EAC RefPack
//! codec — and pin archive parsing, listings, instance routing, path
//! keys and payload decompression.
//!
//! # Data-path discipline
//!
//! This crate is not simulation code, but it keeps the plan's rules
//! anyway (§3.3): `#![forbid(unsafe_code)]`, no global mutable state
//! (the C++ `TheFileSystem`/`TheArchiveFileSystem`/`TheLocalFileSystem`
//! singletons become one owned [`Vfs`]), deterministic listings
//! (ordered sets, never hash iteration), and malformed input is a
//! [`Result`] error where the C++ crashes or reads out of bounds.

