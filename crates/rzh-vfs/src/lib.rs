/// Shared helpers for this crate's unit tests (and nothing else).
#[cfg(test)]
pub(crate) mod test_support {
    /// Builds a BIG archive image from `(stored_path, payload)` pairs,
    /// laid out header → entry table → payloads, exactly like the
    /// shipped format (big-endian offsets/sizes, NUL-terminated paths).
    pub fn build_big(entries: &[(&str, &[u8])]) -> Vec<u8> {
        let mut out = Vec::new();
        out.extend_from_slice(b"BIGF");
        let table_len: usize = entries.iter().map(|(path, _)| 8 + path.len() + 1).sum();
        let total = 16 + table_len + entries.iter().map(|(_, d)| d.len()).sum::<usize>();
        out.extend_from_slice(&(total as u32).to_le_bytes());
        out.extend_from_slice(&(entries.len() as u32).to_be_bytes());
        out.extend_from_slice(&16u32.to_be_bytes());
        let mut at = 16 + table_len as u32;
        for (path, data) in entries {
            out.extend_from_slice(&at.to_be_bytes());
            out.extend_from_slice(&(data.len() as u32).to_be_bytes());
            out.extend_from_slice(path.as_bytes());
            out.push(0);
            at += data.len() as u32;
        }
        for (_, data) in entries {
            out.extend_from_slice(data);
        }
        out
    }
}
